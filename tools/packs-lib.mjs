// Shared by the pack builders: writes assets/pack-<name>.js (a classic script that registers itself on
// globalThis.FNSC_PACKS, so it loads under file:// where fetch and ES-module imports of local files fail) and
// keeps the two manifests in step: assets/packs.json (readable) and src/js/packs-manifest.js (inlined).
//
//   writePack('env', { tiers: ['medium', 'high'], deps: ['three-hi'] }, 'data', '{ lut: "...", ... }')
//
// `kind` 'data' registers a plain object literal; 'code' registers the result of an IIFE body that returns the api.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
export const game = path.join(here, '..');
const assets = path.join(game, 'assets');
const jsonPath = path.join(assets, 'packs.json');
const modPath = path.join(game, 'src', 'js', 'packs-manifest.js');

export function readManifest() {
  try { return JSON.parse(fs.readFileSync(jsonPath, 'utf8')); } catch { return {}; }
}

function writeManifest(m) {
  const sorted = Object.fromEntries(Object.keys(m).sort().map((k) => [k, m[k]]));
  fs.writeFileSync(jsonPath, JSON.stringify(sorted, null, 2) + '\n');
  fs.writeFileSync(modPath, '// GENERATED by tools/packs-lib.mjs from assets/packs.json. Do not edit.\n' +
    `export const PACKS = ${JSON.stringify(sorted)};\n`);
}

export function writePack(name, meta, kind, body, note = '') {
  const hash = crypto.createHash('sha256').update(body).digest('hex').slice(0, 16);
  const m = readManifest();
  const v = m[name] && m[name].hash === hash ? m[name].v : ((m[name] && m[name].v) || 0) + 1;
  const reg = `(globalThis.FNSC_PACKS = globalThis.FNSC_PACKS || {})[${JSON.stringify(name)}]`;
  const data = kind === 'code' ? `(function(){\n${body}\n})()` : body;
  const out = `/* Friday Night Spa City asset pack "${name}" v${v} · ${hash} · ${note || 'generated'} · do not edit */\n` +
    `${reg} = { v: ${v}, hash: ${JSON.stringify(hash)}, data: ${data} };\n`;
  const file = `assets/pack-${name}.js`;
  fs.mkdirSync(assets, { recursive: true });
  fs.writeFileSync(path.join(game, file), out);
  m[name] = { file, v, hash, bytes: Buffer.byteLength(out), tiers: meta.tiers || ['medium', 'high'], deps: meta.deps || [] };
  writeManifest(m);
  return m[name];
}

export const kb = (n) => `${(n / 1024).toFixed(0)} KB`;
