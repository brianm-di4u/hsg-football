#!/usr/bin/env node
// Embeds the packed sky panorama (assets/sky-ridge.webp, from art-src via shared/test-harness/art-pack.mjs) as a
// data URL module. WebGL can't upload images loaded from file:// (they count as cross-origin), but a data URL
// works everywhere. The title art stays a plain file (assets/*.webp), shown with CSS.
//   node tools/build-art.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const game = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const b64 = fs.readFileSync(path.join(game, 'assets', 'sky-ridge.webp')).toString('base64');
const out = `// GENERATED by tools/build-art.mjs from assets/sky-ridge.webp (painted art, art-src/sky-ridge.png). Do not edit.\nexport const SKY_RIDGE = 'data:image/webp;base64,${b64}';\n`;
fs.writeFileSync(path.join(game, 'src', 'js', 'sky-data.js'), out);
console.log(`sky-data.js ${(out.length / 1024).toFixed(1)} KB`);
