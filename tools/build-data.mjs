#!/usr/bin/env node
// Regenerates games/football/data/ from the shared sources (never edits them):
//   data/schools.json  ← shared/data/schools.json (verbatim copy)
//   data/facts.json    ← halftime facts: audited trivia ids (games/trivia/data/questions.json) + two schools.json notes
// Usage: node games/football/tools/build-data.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../..');
const out = path.resolve(here, '../data');
fs.mkdirSync(out, { recursive: true });

const schoolsSrc = fs.readFileSync(path.join(root, 'shared/data/schools.json'), 'utf8');
fs.writeFileSync(path.join(out, 'schools.json'), schoolsSrc);

const bank = JSON.parse(fs.readFileSync(path.join(root, 'games/trivia/data/questions.json'), 'utf8'));
const byId = new Map(bank.questions.map((q) => [q.id, q]));

// Text is a light rewording of each audited explanation (see research/town-content.md §3).
const FACTS = [
  ['hs-0225', ['lakeside'], 'Lakeside High School was founded in 1928.'],
  ['hs-0227', ['hot-springs'], 'Hot Springs shared the 1934 state football title with Blytheville and De Queen.'],
  ['hs-0236', ['lakeside'], 'Lakeside lost the 1975 state football final to Stuttgart, and won the 5A South in 2019.'],
  ['hs-0237', ['hot-springs'], 'The Trojans won state football titles in 1934, 1970 and 1972.'],
  ['hs-0239', ['mountain-pine'], 'Mountain Pine won back-to-back state football titles in 1978 and 1979.'],
  ['hs-0251', ['lake-hamilton'], 'Lake Hamilton won state football titles in 1992 and 2008.'],
  ['hs-0252', ['lakeside', 'lake-hamilton'], 'Lakeside beat Lake Hamilton 49–42 at Wolf Stadium in Pearcy on Aug. 25, 2023.'],
  ['hs-0253', ['lakeside', 'lake-hamilton'], 'The Lakeside–Lake Hamilton series was discontinued after the 1999 season.'],
  ['hs-0254', ['jessieville'], 'Jessieville won the Class 2A state football title in 2006.'],
  ['hs-0255', ['fountain-lake'], 'Fountain Lake won the Class 3A state football title in 2009.'],
  ['hs-0273', ['lakeside'], "Lakeside's colors are blue and gold."],
  ['hs-0274', ['lake-hamilton'], "Lake Hamilton's colors are maroon and gold."],
  ['hs-0275', ['lake-hamilton'], 'Lake Hamilton High School is in Pearcy.'],
  ['hs-0278', ['hot-springs'], "Hot Springs High's colors are black and gold."],
];

const facts = [];
for (const [id, teams, text] of FACTS) {
  const q = byId.get(id);
  if (!q) throw new Error(`audited question ${id} not found`);
  if (q.confidence !== 'confirmed') throw new Error(`${id} is not confirmed (${q.confidence})`);
  facts.push({ id, teams, text, source: q.source });
}
facts.push({ id: 'schools-wagner', teams: ['hot-springs'], text: "Hot Springs High's black and gold trace to 1912, when Honus Wagner bought the team black-and-gold basketball uniforms.", source: 'shared/data/schools.json (Wikipedia: Ban Johnson Park)' });
facts.push({ id: 'schools-cms', teams: ['cutter-morning-star'], text: 'Cutter-Morning Star returned to 11-man football in a 3A-4 league.', source: 'shared/data/schools.json (Fearless Friday)' });

fs.writeFileSync(path.join(out, 'facts.json'), JSON.stringify({ about: 'Halftime facts. Generated by tools/build-data.mjs; do not edit.', facts }, null, 1) + '\n');
console.log(`schools.json copied; ${facts.length} facts written`);
