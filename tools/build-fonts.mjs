#!/usr/bin/env node
// Embeds the vendored OFL fonts (vendor/fonts, from @fontsource on npm) as base64 @font-face rules in
// src/styles/fonts.css, so they load under file:// too (browsers refuse file:// font URLs).
//   node tools/build-fonts.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const game = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const FONTS = [
  ['Graduate', 400, 'graduate-latin-400-normal.woff2'],
  ['Oswald', 500, 'oswald-latin-500-normal.woff2'],
  ['Oswald', 700, 'oswald-latin-700-normal.woff2'],
];
let css = '/* GENERATED by tools/build-fonts.mjs. Graduate (Eduardo Tunni) and Oswald (Vernon Adams et al.), SIL Open Font License 1.1: vendor/fonts. */\n';
for (const [fam, w, file] of FONTS) {
  const b64 = fs.readFileSync(path.join(game, 'vendor', 'fonts', file)).toString('base64');
  css += `@font-face { font-family: "${fam}"; font-style: normal; font-weight: ${w}; font-display: swap; src: url(data:font/woff2;base64,${b64}) format("woff2"); }\n`;
}
fs.writeFileSync(path.join(game, 'src', 'styles', 'fonts.css'), css);
console.log(`fonts.css ${(css.length / 1024).toFixed(1)} KB`);
